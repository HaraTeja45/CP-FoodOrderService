package com.cp.foodordermanagement.bean;

public class PartnerCusineRequestBean {

	private String cusineName;

	private String cusineDescription;

	private String cusineCode;
	
	private String cusineCategory;
	
	private String cusineCatDescription;

	private String status;

	public String getCusineName() {
		return cusineName;
	}

	public void setCusineName(String cusineName) {
		this.cusineName = cusineName;
	}

	public String getCusineDescription() {
		return cusineDescription;
	}

	public void setCusineDescription(String cusineDescription) {
		this.cusineDescription = cusineDescription;
	}

	public String getCusineCode() {
		return cusineCode;
	}

	public void setCusineCode(String cusineCode) {
		this.cusineCode = cusineCode;
	}

	public String getStatus() {
		return status;
	}

	public void setStatus(String status) {
		this.status = status;
	}

	public String getCusineCategory() {
		return cusineCategory;
	}

	public void setCusineCategory(String cusineCategory) {
		this.cusineCategory = cusineCategory;
	}

	public String getCusineCatDescription() {
		return cusineCatDescription;
	}

	public void setCusineCatDescription(String cusineCatDescription) {
		this.cusineCatDescription = cusineCatDescription;
	}
	
	

}
